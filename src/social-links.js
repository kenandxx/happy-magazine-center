export function cleanTalentName(raw = '') {
  return String(raw)
    .replace(/[（(][^）)]*[）)]/g, '')
    .replace(/ほか.*$/g, '')
    .trim();
}

export function buildTalentPromoLinks(item) {
  const talents = (item.coverTalents || [])
    .map(cleanTalentName)
    .filter((name) => name && !/グラビア|合併号|特集/.test(name))
    .slice(0, 3);

  const keywordBase = item.series && item.series !== '写真集' ? item.series : item.title;

  return talents.map((talent) => {
    const xQuery = `${talent} ${keywordBase} (表紙 OR オフショット OR 特典 OR ポストカード OR 写真集) filter:images`;
    const igTag = encodeURIComponent(talent.replace(/\s+/g, ''));
    const webQuery = `${talent} ${item.title} 先行カット OR オフショット`;
    return {
      talent,
      links: [
        {
          platform: 'x',
          label: 'X 写真付き宣伝・オフショット',
          url: `https://x.com/search?q=${encodeURIComponent(xQuery)}&f=live`,
        },
        {
          platform: 'instagram',
          label: 'Instagram タグ/投稿を見る',
          url: `https://www.instagram.com/explore/tags/${igTag}/`,
        },
        {
          platform: 'tiktok',
          label: 'TikTok オフショット動画',
          url: `https://www.tiktok.com/search?q=${encodeURIComponent(`${talent} ${keywordBase}`)}`,
        },
        {
          platform: 'google',
          label: 'Web関連画像まとめ',
          url: `https://www.google.com/search?tbm=isch&q=${encodeURIComponent(webQuery)}`,
        },
      ],
    };
  });
}

export function getOfficialSnsForItem(item) {
  const explicit = item.officialSns || [];
  const fromSeries = MAGAZINE_OFFICIAL_SNS[item.series] || [];
  const seen = new Set();
  const merged = [];
  for (const entry of [...explicit, ...fromSeries]) {
    if (!seen.has(entry.url)) {
      seen.add(entry.url);
      merged.push(entry);
    }
  }
  return merged;
}

